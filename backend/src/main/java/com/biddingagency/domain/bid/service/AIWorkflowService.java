    @Async("llmTaskExecutor")
    public void extractRequirementsAsync(BidRequest bidRequest) {
        UUID bidRequestId = bidRequest.getId();
        Opportunity opp = bidRequest.getOpportunity();
        log.info("[AI] 요구사항 추출 시작: bidRequestId={}, opportunityId={}", bidRequestId, opp.getId());

        try {
            RequirementExtractionRequest request = RequirementExtractionRequest.builder()
                .opportunityId(opp.getId())
                .opportunityText(buildOpportunityText(opp))
                .metadata(Map.of("bidRequestId", bidRequestId.toString()))
                .build();

            RequirementExtractionResponse response = llmPlatformClient.extractRequirements(request);

            if (!"success".equalsIgnoreCase(response.getStatus())) {
                log.error("[AI] 요구사항 추출 실패: bidRequestId={}, error={}", bidRequestId, response.getErrorMessage());
                return;
            }

            // CR-002: Aimbase 워크플로우가 MCP save_requirements를 직접 호출하여 DB에 저장.
            // saveExtractedRequirements() 호출 불필요.
            log.info("[AI] 요구사항 추출 완료 (Aimbase MCP 콜백으로 저장됨): bidRequestId={}", bidRequestId);

        } catch (LLMPlatformException e) {
            log.error("[AI] Aimbase 오류 (요구사항 추출): bidRequestId={}", bidRequestId, e);
        } catch (Exception e) {
            log.error("[AI] 예상치 못한 오류 (요구사항 추출): bidRequestId={}", bidRequestId, e);
        }
    }

